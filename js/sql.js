// sql.js — DDL generation from ERD models (PowerDesigner PDM-style).
// Reads ERDEntity (columns: name/type/primaryKey/notNull/unique/comment)
// and ERDReference views (tail=child, head=parent; fkColumns, cardinalities,
// onDelete/onUpdate) placed on ERD diagrams.

import { repository } from './core/repository.js';

export const SQL_DIALECTS = {
  mysql: 'MySQL',
  postgresql: 'PostgreSQL',
  sqlite: 'SQLite',
  ansi: 'ANSI SQL',
};

function q(dialect, name) {
  if (dialect === 'mysql') return '`' + name + '`';
  if (dialect === 'postgresql') return '"' + name + '"';
  return '"' + name + '"';
}

function comment(dialect, text, indent = '') {
  if (!text) return '';
  const t = String(text).replace(/'/g, "''").replace(/\n/g, ' ');
  if (dialect === 'mysql') return `${indent}COMMENT = '${t}'`;
  return '';
}

function columnComment(dialect, table, col, text) {
  if (!text) return '';
  const t = String(text).replace(/'/g, "''").replace(/\n/g, ' ');
  if (dialect === 'mysql') return ` COMMENT '${t}'`;
  if (dialect === 'postgresql') return '';
  return '';
}

function postComments(dialect, out, table, columns) {
  if (dialect !== 'postgresql') return;
  for (const col of columns) {
    if (col.comment) {
      out.push(`COMMENT ON COLUMN ${q(dialect, table.name)}.${q(dialect, col.name)} IS '${String(col.comment).replace(/'/g, "''")}'`);
    }
  }
  if (table.documentation) {
    out.push(`COMMENT ON TABLE ${q(dialect, table.name)} IS '${String(table.documentation).replace(/'/g, "''")}'`);
  }
}

/**
 * Generate DDL for the given ERD entities + references.
 * entities: ERD model elements with .columns; references: view descriptors
 * { childModel, parentModel, fkColumns, onDelete, onUpdate }.
 * Returns a single SQL script string.
 */
export function generateSQL(entities, references, dialect = 'mysql', views = []) {
  const out = [];
  const head = `-- ${SQL_DIALECTS[dialect] || dialect} DDL generated by OpenUML\n-- ${new Date().toISOString()}\n`;
  out.push(head);

  for (const table of entities) {
    const cols = (table.columns || []).filter((c) => c && c.name);
    if (!cols.length && !(table.columns || []).length) continue;
    const pk = cols.filter((c) => c.primaryKey);
    const lines = [];
    for (const col of cols) {
      let line = `${q(dialect, col.name)} ${col.type || 'VARCHAR(50)'}`;
      if (col.notNull || col.primaryKey) line += ' NOT NULL';
      if (col.unique && !col.primaryKey) line += ' UNIQUE';
      if (col.defaultValue) line += ` DEFAULT ${col.defaultValue}`;
      if (dialect === 'mysql' && col.comment) line += columnComment(dialect, table.name, col, col.comment);
      if (dialect === 'mysql' && col.primaryKey && cols.filter((c) => c.primaryKey).length === 1) line += ' PRIMARY KEY';
      if (dialect === 'sqlite' && col.primaryKey && cols.filter((c) => c.primaryKey).length === 1) line += ' PRIMARY KEY';
      lines.push(line);
    }
    if (pk.length > 1 || (pk.length && dialect === 'postgresql')) {
      lines.push(`PRIMARY KEY (${pk.map((c) => q(dialect, c.name)).join(', ')})`);
    }
    const uniques = cols.filter((c) => c.unique && !c.primaryKey);
    if (uniques.length === 1) {
      // already inline UNIQUE per column
    }
    const tbl = `${q(dialect, table.name)} (\n  ${lines.join(',\n  ')}\n)`;
    let stmt = `CREATE TABLE ${tbl}`;
    if (dialect === 'mysql') {
      const opts = [];
      if (table.documentation) opts.push(comment(dialect, table.documentation, ''));
      if (opts.length) stmt += opts.join('');
    }
    stmt += ';';
    out.push(stmt);
    postComments(dialect, out, table, cols);
  }

  // views: CREATE VIEW from the view's stored SQL text
  for (const view of views) {
    if (!view.sql) continue;
    const body = String(view.sql).trim().replace(/;+$/, '');
    out.push(`CREATE VIEW ${q(dialect, view.name)} AS\n  ${body};`);
  }

  // indexes (table-level INDEX / UNIQUE INDEX definitions)
  for (const table of entities) {
    for (const idx of table.indexes || []) {
      if (!idx.name || !idx.columns) continue;
      const cols = String(idx.columns).split(',').map((x) => x.trim()).filter(Boolean);
      if (!cols.length) continue;
      const kw = idx.unique ? 'CREATE UNIQUE INDEX' : 'CREATE INDEX';
      const naming = dialect === 'postgresql' ? `ON ${q(dialect, table.name)}` : `ON ${q(dialect, table.name)}`;
      out.push(`${kw} ${q(dialect, idx.name)} ${naming} (${cols.map((c) => q(dialect, c)).join(', ')});`);
    }
  }

  // foreign keys from references (tail = child table, head = parent table)
  for (const ref of references) {
    const child = ref.child, parent = ref.parent;
    if (!child || !parent) continue;
    const fkCols = String(ref.fkColumns || '').split(',').map((s) => s.trim()).filter(Boolean);
    if (!fkCols.length) continue;
    const parentCols = String(ref.parentColumns || '').split(',').map((s) => s.trim()).filter(Boolean);
    const targets = parentCols.length ? parentCols : (() => {
      const pt = entities.find((e) => e._id === (ref.parentModelId) || e.name === parent.name);
      return (pt && pt.columns || []).filter((c) => c.primaryKey).map((c) => c.name);
    })();
    const fkName = `fk_${child.name}_${parent.name}`.replace(/[^\p{L}\p{N}_]/gu, '_');
    out.push(`ALTER TABLE ${q(dialect, child.name)} ADD CONSTRAINT ${q(dialect, fkName)}\n  FOREIGN KEY (${fkCols.map((c) => q(dialect, c)).join(', ')})\n  REFERENCES ${q(dialect, parent.name)} (${(targets.length ? targets : fkCols).map((c) => q(dialect, c)).join(', ')})\n  ON DELETE ${ref.onDelete || 'RESTRICT'}\n  ON UPDATE ${ref.onUpdate || 'RESTRICT'};`);
  }

  return out.join('\n\n') + '\n';
}

/** Collect ERD content from a diagram: entities (models) + reference descriptors. */
export function collectERD(diagram) {
  const entities = [];
  const references = [];
  if (!diagram) return { entities, references };
  const entityIds = new Map();
  for (const v of diagram.elements || []) {
    if (v.$type === 'ERDEntity') {
      const m = repository.lookup(v.modelRef);
      if (m) { entities.push(m); entityIds.set(v._id, m); }
    }
  }
  for (const v of diagram.elements || []) {
    if (v.$type !== 'ERDReference' && v.$type !== 'ERDRelationship') continue;
    const childView = repository.lookup(v.tail);
    const parentView = repository.lookup(v.head);
    const child = childView ? repository.lookup(childView.modelRef) : null;
    const parent = parentView ? repository.lookup(parentView.modelRef) : null;
    if (child && parent) {
      references.push({
        child, parent,
        childModelId: child._id, parentModelId: parent._id,
        fkColumns: v.fkColumns || '',
        parentColumns: v.parentColumns || '',
        onDelete: v.onDelete, onUpdate: v.onUpdate,
      });
    }
  }
  return { entities, references };
}

/**
 * CDM→PDM transform: for each ERDRelationship, generate FK column(s) on the
 * child entity based on the parent's primary-key columns and the cardinality.
 * Returns a list of { entity, col } and applies them through `apply`.
 */
export function cdmToPDM(diagram, apply) {
  const { entities, references } = collectERD(diagram);
  const byId = new Map(entities.map((e) => [e._id, e]));
  const changes = [];
  for (const ref of references) {
    const child = byId.get(ref.childModelId);
    const parent = ref.parent;
    if (!child || !parent) continue;
    const parentPK = (parent.columns || []).filter((c) => c.primaryKey);
    if (!parentPK.length) continue;
    const existing = new Set((child.columns || []).map((c) => c.name.toLowerCase()));
    // referenced views may carry explicit FK column names
    const refView = (diagram.elements || []).find((v) => v.$type === 'ERDReference' &&
      byId.get(v.tail) === child && byId.get(v.head) === parent);
    const fkNames = String(refView?.fkColumns || '').split(',').map((x) => x.trim()).filter(Boolean);
    const cols = parentPK.map((pk, i) => ({
      name: fkNames[i] || `${snake(parent.name)}_${pk.name}`,
      type: pk.type || 'BIGINT',
      primaryKey: false,
      notNull: !/^(0\.\.*)/i.test(String(ref.headCardinality || '')),
      unique: false,
      foreignKey: true,
    })).filter((c) => !existing.has(c.name.toLowerCase()));
    if (!cols.length) continue;
    changes.push({ child, cols, ref, parent });
  }
  if (apply && changes.length) {
    for (const ch of changes) {
      ch.child.columns = [...(ch.child.columns || []), ...ch.cols];
      for (const col of ch.cols) col.foreignKey = true;
    }
  }
  return changes;
}

function snake(name) {
  const raw = String(name || 'ref').trim();
  // keep CJK and other Unicode letters; only replace true separators
  const sn = raw.replace(/[^\p{L}\p{N}_]+/gu, '_').replace(/_+/g, '_').replace(/^_|_$/g, '');
  return sn || raw.replace(/\s+/g, '_');
}


/**
 * Reverse-engineer a SQL script into ERD entities/references (offline parse,
 * no database connection). Supports CREATE TABLE with column lines and
 * table-level PRIMARY KEY / FOREIGN KEY / UNIQUE clauses, plus
 * ALTER TABLE ... ADD CONSTRAINT ... FOREIGN KEY. Dialect quirks
 * (backticks, COMMENT clauses, ENGINE suffix) are tolerated.
 * Returns { entities: [model-like], references: [...] } (plain objects).
 */
export function parseSQL(text) {
  const entities = [];
  const references = [];
  const script = String(text || '').replace(/--[^\n]*/g, '').replace(/\/\*[\s\S]*?\*\//g, '');
  const statements = script.split(';').map((s) => s.trim()).filter(Boolean);
  const tableRe = /CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?[`"[]?([\w.$]+)[`"\]]?\s*\([\s\S]*\)/i;
  const tableNameRe = /CREATE\s+TABLE\s+(?:IF\s+NOT\s+EXISTS\s+)?[`"[]?([\w.$]+)[`"\]]?/i;
  const alterRe = /ALTER\s+TABLE\s+(?:ONLY\s+)?[`"[]?([\w.$]+)[`"\]]?\s*ADD\s+CONSTRAINT\s+[`"[]?(\w+)[`"\]]?\s+FOREIGN\s+KEY\s*\(([^)]*)\)\s*REFERENCES\s+[`"[]?([\w.$]+)[`"\]]?\s*\(([^)]*)\)(?:\s*ON\s+DELETE\s+(\w+(?:\s+NULL)?))?(?:\s*ON\s+UPDATE\s+(\w+(?:\s+NULL)?))?/i;

  const parseCols = (body, tableName) => {
    // split on top-level commas (respect parentheses like DECIMAL(10,2))
    const parts = [];
    let depth = 0, cur = '';
    for (const ch of body) {
      if (ch === '(') depth++;
      if (ch === ')') depth--;
      if (ch === ',' && depth === 0) { parts.push(cur); cur = ''; } else cur += ch;
    }
    if (cur.trim()) parts.push(cur);
    const columns = [];
    const tablePK = [];
    const tableUnique = [];
    for (const raw of parts) {
      const part = raw.trim().replace(/,$/, '');
      if (!part) continue;
      const head = part.split(/\s+/)[0].replace(/[`"[]|[`"\]]/g, '');
      const upper = part.toUpperCase();
      if (/^(PRIMARY\s+KEY|FOREIGN\s+KEY|CONSTRAINT|UNIQUE|INDEX|KEY|CHECK)\b/.test(upper)) {
        const pkCols = upper.startsWith('PRIMARY KEY') ? extractCols(part) : null;
        if (pkCols) tablePK.push(...pkCols);
        if (upper.startsWith('UNIQUE') || upper.startsWith('INDEX') || upper.startsWith('KEY')) {
          const u = extractCols(part);
          if (u) tableUnique.push(...u);
        }
        const fk = upper.startsWith('FOREIGN KEY') || upper.startsWith('CONSTRAINT')
          ? parseInlineFK(part, tableName) : null;
        if (fk) references.push(fk);
        continue;
      }
      const typeM = part.match(new RegExp('^' + quote(head) + '\\s+([\\w]+(?:\\s*\\([^)]*\\))?)', 'i'));
      const col = {
        _id: 'col-' + Math.random().toString(36).slice(2, 9),
        name: head,
        type: typeM ? typeM[1].replace(/\s+/g, ' ').trim() : '',
        primaryKey: /PRIMARY\s+KEY/.test(upper),
        notNull: /NOT\s+NULL/.test(upper) || /PRIMARY\s+KEY/.test(upper),
        unique: /UNIQUE/.test(upper),
      };
      const cm = part.match(/COMMENT\s+'([^']*)'/i);
      if (cm) col.comment = cm[1];
      const dm = part.match(/DEFAULT\s+([^,\s][^,]*)/i);
      if (dm) col.defaultValue = dm[1].trim();
      columns.push(col);
    }
    for (const name of tablePK) {
      const col = columns.find((c) => c.name.toLowerCase() === name.toLowerCase());
      if (col) { col.primaryKey = true; col.notNull = true; }
    }
    for (const name of tableUnique) {
      const col = columns.find((c) => c.name.toLowerCase() === name.toLowerCase());
      if (col && !col.primaryKey) col.unique = true;
    }
    return columns;
  };

  const extractCols = (part) => {
    const m = part.match(/\(([^)]*)\)/);
    if (!m) return [];
    return m[1].split(',').map((s) => s.trim().replace(/[`"[]|[`"\]]/g, '')).filter(Boolean);
  };
  const parseInlineFK = (part, tableName) => {
    const m = part.match(/FOREIGN\s+KEY\s*\(([^)]*)\)\s*REFERENCES\s+[`"[]?([\w.$]+)[`"\]]?\s*(?:\(([^)]*)\))?/i);
    if (!m) return null;
    const od = part.match(/ON\s+DELETE\s+(\w+(?:\s+NULL)?)/i);
    const ou = part.match(/ON\s+UPDATE\s+(\w+(?:\s+NULL)?)/i);
    return {
      childTable: tableName,
      parentTable: m[2],
      fkColumns: (m[1] || '').trim(),
      parentColumns: (m[3] || '').trim(),
      onDelete: od ? od[1].toUpperCase() : 'RESTRICT',
      onUpdate: ou ? ou[1].toUpperCase() : 'RESTRICT',
    };
  };
  const quote = (s) => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');

  for (const stmt of statements) {
    if (!/CREATE\s+TABLE/i.test(stmt)) continue;
    const nameM = stmt.match(tableNameRe);
    if (!nameM) continue;
    const open = stmt.indexOf('(');
    const close = stmt.lastIndexOf(')');
    if (open < 0 || close <= open) continue;
    const body = stmt.slice(open + 1, close);
    const columns = parseCols(body, nameM[1]);
    entities.push({
      _id: 'e-' + Math.random().toString(36).slice(2, 10),
      type: 'ERDEntity',
      name: nameM[1],
      columns,
      documentation: '',
      ownedElements: [],
    });
  }
  // ALTER-based FKs
  for (const stmt of statements) {
    const am = stmt.match(alterRe);
    if (!am) continue;
    references.push({
      childTable: am[1],
      constraintName: am[2],
      fkColumns: am[3],
      parentTable: am[4],
      parentColumns: am[5],
      onDelete: am[6] || 'RESTRICT',
      onUpdate: am[7] || 'RESTRICT',
    });
  }
  // inline FKs collected during column parsing: attach child table names later
  return { entities, references };
}

/**
 * Import a parsed SQL script into a diagram as entities + reference views.
 * Returns the created model elements (already added to the repository).
 */
export function importSQLToDiagram(diagram, text, addModel, createNodeView, createEdgeView) {
  const parsed = parseSQL(text);
  const created = [];
  const byTable = new Map();
  let x = 60, y = 60;
  for (const e of parsed.entities) {
    addModel(e);
    const v = createNodeView('ERDEntity', e._id, x, y, { width: 220 });
    diagram.elements.push(v);
    byTable.set(e.name.toLowerCase(), v);
    created.push(v);
    x = x >= 700 ? 60 : x + 300;
    if (x < 60) x = 60; else if (x > 720) { x = 60; y += 220; }
  }
  // resolve references (inline FKs were normalized into `references`)
  const tables = new Map(parsed.entities.map((e) => [e.name.toLowerCase(), e]));
  for (const ref of parsed.references) {
    const childTable = tables.get(String(ref.childTable).toLowerCase());
    const parentTable = tables.get(String(ref.parentTable).toLowerCase());
    if (!childTable || !parentTable) continue;
    const childView = byTable.get(ref.childTable.toLowerCase());
    const parentView = byTable.get(ref.parentTable.toLowerCase());
    if (!childView || !parentView) continue;
    const m = {
      _id: 'r-' + Math.random().toString(36).slice(2, 10),
      type: 'ERDReference', name: '', stereotype: '', documentation: '', ownedElements: [],
    };
    addModel(m);
    const v = createEdgeView('ERDReference', m._id, childView._id, parentView._id);
    v.fkColumns = ref.fkColumns || '';
    v.parentColumns = ref.parentColumns || '';
    v.onDelete = ref.onDelete || 'RESTRICT';
    v.onUpdate = ref.onUpdate || 'RESTRICT';
    diagram.elements.push(v);
    created.push(v);
  }
  return created;
}
